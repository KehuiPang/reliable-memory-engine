#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
V2 干净知识集:跨领域、语义有区分度(吸取V1教训:不再造近乎重复的模板句)。
每条知识独立、彼此语义差异大;paraphrase自然改写。
用【实体×属性】组合,但实体来自多个不同领域、属性多样,保证语义分散。
"""
import random
random.seed(7)

# 多领域实体-事实(每条语义独立)。用不同模板+不同主题,避免雷同。
# 结构: (主题词, 问题模板函数, 答案, paraphrase模板列表)

def make_pool():
    pool = []

    # 领域1: 国家-首都(20条,各不相同)
    caps = {"中国":"北京","日本":"东京","法国":"巴黎","英国":"伦敦","德国":"柏林",
            "意大利":"罗马","西班牙":"马德里","俄罗斯":"莫斯科","埃及":"开罗","印度":"新德里",
            "巴西":"巴西利亚","加拿大":"渥太华","澳大利亚":"堪培拉","韩国":"首尔","泰国":"曼谷",
            "希腊":"雅典","土耳其":"安卡拉","阿根廷":"布宜诺斯艾利斯","南非":"比勒陀利亚","墨西哥":"墨西哥城"}
    for c, cap in caps.items():
        pool.append((f"{c}的首都是哪座城市", cap,
                     [f"{c}的首都叫什么", f"{c}的都城是哪里", f"{c}政府所在的城市是"]))

    # 领域2: 科学常识(各不同)
    sci = [("水的沸点在标准大气压下是多少","100摄氏度",["水在一个大气压下几度沸腾","标准气压下水的沸点","水烧开是多少度"]),
           ("光在真空中的速度约是多少","每秒约30万公里",["真空里光速是多少","光传播多快","光在真空中的速率"]),
           ("人类正常体温大约是多少","37摄氏度",["人的正常体温是几度","健康人体温大概多少","人体标准温度"]),
           ("地球自转一周需要多长时间","约24小时",["地球转一圈多久","地球自转周期是多长","一天有多长因为地球转"]),
           ("声音在空气中的传播速度约是","每秒340米",["空气里声速是多少","声音在空气中跑多快","音速大约多少"]),
           ("成年人的骨骼总数是多少","206块",["人有多少块骨头","成人骨头数量","人体骨骼共几块"]),
           ("血液中运输氧气的细胞是","红细胞",["哪种血细胞运氧","负责携氧的血细胞是","血里带氧的细胞"]),
           ("植物光合作用吸收的气体是","二氧化碳",["光合作用吸进什么气","植物白天吸收哪种气体","光合作用的原料气体"])]
    for q,a,p in sci: pool.append((q,a,p))

    # 领域3: 历史/文化(各不同)
    his = [("万里长城主要修建于哪个朝代","秦朝及以后多朝",["长城是哪个朝代建的","修长城的朝代","长城始建于什么时候"]),
           ("莎士比亚是哪国的剧作家","英国",["莎士比亚是哪国人","写哈姆雷特的作家是哪国的","莎翁国籍"]),
           ("金字塔最著名的位于哪个国家","埃及",["大金字塔在哪个国家","著名金字塔位于何处","胡夫金字塔在哪国"]),
           ("印刷术是哪个国家发明的","中国",["活字印刷谁发明的国家","印刷术起源国","哪国发明了印刷"]),
           ("文艺复兴最早兴起于哪个国家","意大利",["文艺复兴发源地","文艺复兴起源国","哪国最早文艺复兴"])]
    for q,a,p in his: pool.append((q,a,p))

    # 领域4: 生物(动物特征,各不同)
    bio = [("哪种动物被称为森林之王","老虎",["森林之王指哪种动物","被叫森林之王的是","哪个动物号称林中王"]),
           ("企鹅主要生活在地球的哪个半球","南半球",["企鹅住在南半球还是北半球","企鹅栖息在哪个半球","企鹅分布的半球"]),
           ("蜜蜂采集花蜜主要用来做什么","酿蜜",["蜜蜂采蜜干嘛","蜜蜂收集花蜜的用途","花蜜被蜜蜂拿来"]),
           ("变色龙最著名的能力是什么","变色",["变色龙有什么特殊本领","变色龙擅长什么","变色龙以什么著称"]),
           ("骆驼能长时间不喝水靠的是","驼峰储存脂肪",["骆驼耐渴靠什么","骆驼不喝水的秘密","驼峰的作用"])]
    for q,a,p in bio: pool.append((q,a,p))

    # 领域5: 技术/日常(各不同)
    tech = [("互联网上网页地址通常以什么开头","http或https",["网址一般以什么开头","网页链接开头是","浏览器地址栏开头"]),
            ("电脑存储容量的基本单位是","字节",["计算机存储最小单位","电脑容量单位是什么","存储的基本单位"]),
            ("智能手机定位主要依靠什么系统","GPS",["手机导航靠什么定位","手机定位用的系统","手机怎么知道位置"]),
            ("电池的正极通常标记为什么符号","加号",["电池正极符号","电池哪端是加号","正极用什么标记"]),
            ("红绿灯中表示通行的是什么颜色","绿色",["交通灯哪个颜色能走","可以通行的信号灯色","走的灯是什么颜色"])]
    for q,a,p in tech: pool.append((q,a,p))

    # 为凑更多数量,用【不同城市×不同独立属性】组合(但每条属性不同,不重复)
    cities = ["巴黎","东京","纽约","伦敦","悉尼","开罗","里约","迪拜","新加坡","伊斯坦布尔",
              "曼谷","罗马","巴塞罗那","阿姆斯特丹","布拉格","维也纳","雅典","里斯本","赫尔辛基","威尼斯"]
    landmarks = ["埃菲尔铁塔","东京塔","自由女神像","大本钟","悉尼歌剧院","金字塔","基督像","哈利法塔",
                 "鱼尾狮","蓝色清真寺","大皇宫","斗兽场","圣家堂","风车","查理大桥","美泉宫","卫城","大耶稣像","岩石教堂","叹息桥"]
    for c, lm in zip(cities, landmarks):
        pool.append((f"{c}最著名的地标建筑是什么", lm,
                     [f"{c}的标志性建筑是", f"提到{c}会想到哪个地标", f"{c}最有名的建筑"]))

    random.shuffle(pool)
    return pool

def gen_knowledge_v2(n_target=None):
    pool = make_pool()
    items = []
    for q, a, paras in pool:
        items.append({"q": q, "a": a, "src": "clean", "paraphrases": paras})
    if n_target: items = items[:n_target]
    return items

def gen_unknown_v2(n=40):
    """语义相关但内容全新的unknown(测抗幻觉),覆盖各领域"""
    unk = ["虚构国瓦坎达的首都是哪座城市","以太星的沸点在标准大气压下是多少",
           "梦境剧作家幻影是哪国的","星港最著名的地标建筑是什么",
           "反物质动物被称为什么之王","泽塔粒子在真空中的速度约是多少",
           "第九维度的自转一周需要多长时间","幻能矿采集主要用来做什么",
           "银河议会最早兴起于哪个国家","时间旅行者协会的定位靠什么系统",
           "2150年火星联邦的首都是哪","龙族语言的字节单位是什么",
           "潘多拉森林之王是哪种生物","星尘城的标志性建筑是",
           "以太网页地址通常以什么开头(指虚构以太网络)","反重力电池的正极符号是什么"]
    random.shuffle(unk)
    return unk[:n]

if __name__ == "__main__":
    k = gen_knowledge_v2()
    u = gen_unknown_v2()
    print(f"V2知识 {len(k)} 条(跨领域,语义有区分度), unknown {len(u)} 条")
    for x in k[:3]: print("  ", x["q"], "→", x["a"])
